#!/usr/bin/env python3
"""Validate and pack the rendered ignition/loop for the GTK fire overlay."""

import argparse
from pathlib import Path
import sys
from PIL import Image

sys.dont_write_bytecode = True
from fire_config import (
    FPS, INTRO, LOOP, WIDTH, HEIGHT, PADDING_X, PADDING_Y,
    SLICE_X, SLICE_Y, CORNER,
)
PREFIX = "/io/github/kristopher/DestructiveConfirm"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("frames", type=Path)
    parser.add_argument("--data", type=Path, default=(
        Path(__file__).resolve().parents[1] / "data/presets/tall-ring"))
    args = parser.parse_args()
    # Validate the complete render before changing any shipped assets.
    images = []
    for frame in range(INTRO + LOOP):
        with Image.open(args.frames / f"{frame:03d}.png") as source:
            if source.size != (WIDTH, HEIGHT) or source.mode != "RGBA":
                raise ValueError(f"Unexpected frame format: {frame}")
            image = source.copy()
        if image.getpixel((WIDTH // 2, HEIGHT // 2))[3] != 0:
            raise ValueError(f"Frame {frame} obscures the button label")
        images.append(image)
    destination = args.data / "fire"
    destination.mkdir(parents=True, exist_ok=True)
    for frame, image in enumerate(images):
        # Re-encoding strips Blender's timestamps and any other PNG metadata.
        clean = Image.new("RGBA", image.size)
        clean.paste(image)
        # Cycles leaves noisy RGB below zero alpha. Those invisible samples
        # otherwise dominate the PNG size; clearing them is visually lossless.
        transparent = clean.getchannel("A").point(lambda alpha: 255 if alpha == 0 else 0)
        clean.paste((0, 0, 0, 0), mask=transparent)
        clean.save(destination / f"{frame:03d}.png", optimize=True)
    constants = {
        "FPS": FPS, "INTRO_FRAMES": INTRO, "LOOP_FRAMES": LOOP,
        "FRAME_WIDTH": WIDTH, "FRAME_HEIGHT": HEIGHT,
        "PADDING_X": PADDING_X, "PADDING_Y": PADDING_Y,
        "SLICE_X": SLICE_X, "SLICE_Y": SLICE_Y, "CORNER": CORNER,
    }
    (args.data / "fire-art.h").write_text(
        "/* Generated by art/pack-fire.py from art/fire_config.py. */\n"
        "#ifndef FIRE_ART_H\n#define FIRE_ART_H\n"
        + "".join(f"#define FIRE_{name} {value}\n"
                  for name, value in constants.items())
        + "#endif\n"
    )
    files = (
        '    <file compressed="true">style.css</file>\n'
        + "".join(f'    <file>fire/{frame:03d}.png</file>\n'
                  for frame in range(INTRO + LOOP))
    )
    (args.data / "destructive-confirm.gresource.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<gresources>\n'
        f'  <gresource prefix="{PREFIX}">\n'
        + files
        + '  </gresource>\n</gresources>\n'
    )
    print(f"Packed {len(images)} original Blender frames; "
          f"{sum(path.stat().st_size for path in destination.glob('*.png')):,} bytes")


if __name__ == "__main__":
    main()
