#!/usr/bin/env python3
"""Pack fluid-rendered fire and make its turbulent burn loop continuous."""

import argparse
from pathlib import Path
import sys
from PIL import Image, ImageChops

sys.dont_write_bytecode = True
from fire_config import (
    FPS, INTRO, LOOP, SEAM_BLEND, EDGE_FADE, WIDTH, HEIGHT, PADDING_X, PADDING_Y,
    SLICE_X, SLICE_Y, CORNER,
)

PREFIX = "/io/github/kristopher/DestructiveConfirm"


def smooth(value):
    return value * value * (3 - 2 * value)


def loop_frame(images, index):
    start = INTRO + LOOP - SEAM_BLEND
    if index < start:
        return images[index]
    previous = INTRO - SEAM_BLEND + index - start
    weight = smooth((index - start + 1) / SEAM_BLEND)
    if index == INTRO + LOOP - 1:
        return images[INTRO - 1].copy()
    # Blend premultiplied alpha, not the undefined RGB under transparent pixels.
    return Image.blend(images[index].convert("RGBa"),
                       images[previous].convert("RGBa"), weight).convert("RGBA")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("frames", type=Path)
    parser.add_argument("--data", type=Path, default=(
        Path(__file__).resolve().parents[2] / "data/presets/real-fire"))
    args = parser.parse_args()
    images = []
    for frame in range(INTRO + LOOP):
        with Image.open(args.frames / f"{frame:03d}.png") as source:
            if source.size != (WIDTH, HEIGHT) or source.mode != "RGBA":
                raise ValueError(f"Unexpected frame format: {frame}")
            image = source.copy()
        if image.getpixel((WIDTH // 2, HEIGHT // 2))[3] != 0:
            raise ValueError(f"Frame {frame} obscures the button label")
        images.append(image)
    destination = args.data / "fire"
    destination.mkdir(parents=True, exist_ok=True)
    # A soft sampling gutter avoids a hard cut when an occasional hot wisp
    # reaches the shallow simulation domain's boundary.
    gutter = Image.frombytes("L", (WIDTH, HEIGHT), bytes(
        round(255 * smooth(min(1, min(x, y, WIDTH - 1 - x,
                                      HEIGHT - 1 - y) / EDGE_FADE)))
        for y in range(HEIGHT) for x in range(WIDTH)))
    for frame in range(len(images)):
        image = loop_frame(images, frame)
        clean = Image.new("RGBA", image.size)
        clean.paste(image)
        clean.putalpha(ImageChops.multiply(clean.getchannel("A"), gutter))
        transparent = clean.getchannel("A").point(lambda a: 255 if a == 0 else 0)
        clean.paste((0, 0, 0, 0), mask=transparent)
        clean.save(destination / f"{frame:03d}.png", optimize=True)
    constants = {
        "FPS": FPS, "INTRO_FRAMES": INTRO, "LOOP_FRAMES": LOOP,
        "FRAME_WIDTH": WIDTH, "FRAME_HEIGHT": HEIGHT,
        "PADDING_X": PADDING_X, "PADDING_Y": PADDING_Y,
        "SLICE_X": SLICE_X, "SLICE_Y": SLICE_Y, "CORNER": CORNER,
    }
    (args.data / "fire-art.h").write_text(
        "/* Generated by art/real-fire/pack-fire.py from its fire_config.py. */\n"
        "#ifndef FIRE_ART_H\n#define FIRE_ART_H\n"
        + "".join(f"#define FIRE_{name} {value}\n"
                  for name, value in constants.items()) + "#endif\n")
    files = ('    <file compressed="true">style.css</file>\n'
             + "".join(f'    <file>fire/{i:03d}.png</file>\n'
                       for i in range(INTRO + LOOP)))
    (args.data / "destructive-confirm.gresource.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n<gresources>\n'
        f'  <gresource prefix="{PREFIX}">\n{files}'
        '  </gresource>\n</gresources>\n')
    print(f"Packed {len(images)} fluid fire frames; "
          f"{sum(p.stat().st_size for p in destination.glob('*.png')):,} bytes")


if __name__ == "__main__":
    main()
