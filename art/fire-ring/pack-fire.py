"""Validate rendered frames and embed the ignition/loop as GTK border images."""

import argparse
from pathlib import Path
from PIL import Image


INTRO = 36
LOOP = 48
PREFIX = "/io/github/kristopher/DestructiveConfirm"


def image_rule(frame):
    return f'border-image-source: url("resource://{PREFIX}/fire/{frame:03d}.png");'


def keyframes(name, first, count, repeat):
    lines = [f"@keyframes {name} {{"]
    for index in range(count):
        lines.append(f"  {100 * index / count:.6f}% {{ {image_rule(first + index)} }}")
    last = first if repeat else first + count - 1
    lines.append(f"  100% {{ {image_rule(last)} }}")
    lines.append("}")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("frames", type=Path)
    parser.add_argument("--data", type=Path, default=(
        Path(__file__).resolve().parents[2] / "data/presets/fire-ring"))
    args = parser.parse_args()
    # Validate the complete render before changing any shipped assets.
    images = []
    for frame in range(INTRO + LOOP):
        with Image.open(args.frames / f"{frame:03d}.png") as source:
            if source.size != (384, 128) or source.mode != "RGBA":
                raise ValueError(f"Unexpected frame format: {frame}")
            image = source.copy()
        if image.getpixel((192, 64))[3] != 0:
            raise ValueError(f"Frame {frame} obscures the button label")
        images.append(image)
    destination = args.data / "fire"
    destination.mkdir(parents=True, exist_ok=True)
    for frame, image in enumerate(images):
        # Re-encoding strips Blender's timestamps and any other PNG metadata.
        clean = Image.new("RGBA", image.size)
        clean.paste(image)
        clean.save(destination / f"{frame:03d}.png", optimize=True)
    css = (
        "/* Generated by art/pack-fire.py; frames rendered by art/render-fire.py. */\n"
        ".destructive-confirm-animated button.destructive-action {\n"
        "  animation: fire-ignite 1.5s steps(36, end) 1 both,\n"
        "             fire-burn 2s steps(48, end) 1.5s infinite;\n"
        "}\n\n"
        + keyframes("fire-ignite", 0, INTRO, False) + "\n\n"
        + keyframes("fire-burn", INTRO, LOOP, True) + "\n"
    )
    (args.data / "fire-animation.css").write_text(css)
    files = (
        '    <file compressed="true">style.css</file>\n'
        '    <file compressed="true">fire-animation.css</file>\n'
        + "".join(f'    <file>fire/{frame:03d}.png</file>\n'
                  for frame in range(INTRO + LOOP))
    )
    (args.data / "destructive-confirm.gresource.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<gresources>\n'
        f'  <gresource prefix="{PREFIX}">\n'
        + files
        + '  </gresource>\n</gresources>\n'
    )
    print(f"Packed {len(images)} original Blender frames; "
          f"{sum(path.stat().st_size for path in destination.glob('*.png')):,} bytes")


if __name__ == "__main__":
    main()
